export function buildPrompt(req: MentorRequest): string {
  const history = req.messages
    .slice(-12)
    .map((m) => `${m.role === 'user' ? 'Ученик' : 'Ментор'}: ${m.text}`)
    .join('\n\n');
  return [
    '<контекст_урока>',
    JSON.stringify(req.context, null, 1).slice(0, 14000),
    '</контекст_урока>',
    '<прогресс_ученика>',
    JSON.stringify(req.progress, null, 1).slice(0, 5000),
    '</прогресс_ученика>',
    req.allowSolution ? 'Ученик ЯВНО попросил готовое решение — дай его с объяснением.' : 'Ученик НЕ просил готовое решение — веди наводящими вопросами и подсказками, не выдавай полную команду/ответ.',
    '<диалог>',
    history,
    '</диалог>',
    'Ответь на последнюю реплику ученика как ментор.',
  ].join('\n');
}

export function validateRequest(body: unknown): MentorRequest {
  const b = body as Partial<MentorRequest>;
  if (!b || !Array.isArray(b.messages) || !b.messages.length) throw new Error('messages required');
  return {
    messages: b.messages.filter((m) => m && typeof m.text === 'string').map((m) => ({ role: m.role === 'assistant' ? 'assistant' : 'user', text: m.text.slice(0, 4000) })),
    context: typeof b.context === 'object' && b.context ? b.context : {},
    progress: typeof b.progress === 'object' && b.progress ? b.progress : {},
    allowSolution: !!b.allowSolution,
  };
}
