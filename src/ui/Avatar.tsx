export function Avatar({ stage, size = 160, title }: { stage: number; size?: number; title?: string }) {
  const rects = STAGES[Math.min(Math.max(stage, 1), 8) - 1];
  return (
    <svg className="avatar" width={size} height={(size * 32) / 24} viewBox="0 0 24 32" role="img" aria-label={title ?? `Аватар, стадия ${stage}`} shapeRendering="crispEdges">
      {rects.map(([x, y, w, h, c], i) => (
        <rect key={i} x={x} y={y} width={w} height={h} fill={c} />
      ))}
    </svg>
  );
}
